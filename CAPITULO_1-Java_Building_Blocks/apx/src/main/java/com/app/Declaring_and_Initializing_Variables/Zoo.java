package com.app.Declaring_and_Initializing_Variables;

public class Zoo {
    //Para declarar una variable se necesita indicar el tipo de dato de la variable, y también el nombre de la variable
    String ZooName; //El tipo de dato es String o Cadena de Texto y su nombre de la variable es ZooName
    int NumberAnimals; //El tipo de dato es entero y el nombre es NumberAnimals

    //Ahora, para inicializar una variable se debe colocar un signo igual ( Asignación ) y colocarle el valor deseado
    //de acuerdo al tipo de dato que se le ha especificado. Para inicializarlo puede estar dentro de un bloque inicializador o un constructor
    
    {ZooName = "Animal Planet";
    NumberAnimals = 100;}

    //Pero, también se puede colocarlo en la misma declaración de la variable, para ahorrar espacio y tiempo
    /* String ZooName "Animal Planet";
    int NumberAnimals = 100 ; */

}
